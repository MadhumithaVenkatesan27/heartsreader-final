/** npm run seed — creates an admin, a licensor and a sample title with 3 tiny PDF chapters. Safe to re-run. */
const fs = require('fs');
const path = require('path');
const bcrypt = require('bcryptjs');
const mongoose = require('mongoose');
const PDFDocument = require('pdfkit');
const config = require('../src/config');
const User = require('../src/models/User');
const Book = require('../src/models/Book');

function makePdf(file, title) {
  return new Promise((resolve) => {
    const doc = new PDFDocument();
    const out = fs.createWriteStream(file);
    doc.pipe(out);
    doc.fontSize(24).text(title).moveDown().fontSize(12).text('Sample chapter generated by the seed script.');
    doc.end();
    out.on('finish', resolve);
  });
}

async function upsertUser(query, data) {
  let u = await User.findOne(query);
  if (!u) u = new User(data);
  Object.assign(u, data, { isEmailVerified: true });
  await u.save();
  return u;
}

(async () => {
  await mongoose.connect(config.mongoUri);
  fs.mkdirSync(config.uploadsDir, { recursive: true });

  const adminEmail = (process.env.SEED_ADMIN_EMAIL || 'admin@example.com').toLowerCase();
  const adminPw = process.env.SEED_ADMIN_PASSWORD || 'ChangeMe-Admin-123';
  await upsertUser({ email: adminEmail }, { name: 'Admin', email: adminEmail, role: 'admin', passwordHash: await bcrypt.hash(adminPw, 12) });
  const licensor = await upsertUser({ licensorId: 'demo-licensor' }, { name: 'Demo Licensor', email: 'licensor@example.com', role: 'licensor', licensorId: 'demo-licensor', passwordHash: await bcrypt.hash('Licensor-Demo-123', 12) });

  // Titles named the way the static frontend refers to them (slug + the "-v1" style ids it uses)
  const titles = [
    { slug: 'the-matchmaker-s-fiance-vol-1', aliases: ['matchmaker-v1', 'matchmaker'], title: "The Matchmaker's Fiancé Vol.1", category: 'Manga', genres: ['Romance', 'Comedy'] },
    { slug: 'you-re-way-too-cheeky-chigaya-kun-vol-1', aliases: ['chigaya-v1', 'chigaya'], title: "You're Way Too Cheeky, Chigaya-kun! Vol.1", category: 'Manga', genres: ['Romance', 'School Life'] },
    { slug: 'you-re-way-too-cheeky-chigaya-kun-vol-2', aliases: ['chigaya-v2'], title: "You're Way Too Cheeky, Chigaya-kun! Vol.2", category: 'Manga', genres: ['Romance', 'School Life'] },
    { slug: 'the-executioner-of-grenimal-vol-1', aliases: ['grenimal-v1', 'executioner'], title: 'The Executioner of Grenimal Vol.1', category: 'Manga', genres: ['Action', 'Fantasy'] },
  ];
  for (const t of titles) {
    if (await Book.findOne({ slug: t.slug })) continue;
    const chapters = [];
    for (let i = 1; i <= 3; i += 1) {
      const pdfFile = `seed-${t.aliases[0]}-ch${i}.pdf`;
      await makePdf(path.join(config.uploadsDir, pdfFile), `${t.title} — Chapter ${i}`);
      chapters.push({ order: i, title: `Chapter ${i}`, free: i === 1, pdfFile, pageCount: 1 });
    }
    await Book.create({
      ...t, description: 'Seeded title for testing.', chapters, licensors: [licensor._id],
      pricing: { chapterUSD: 0.75, chapterINR: 59, fullUSD: 6, fullINR: 449 },
    });
  }
  console.log(`Seeded.\n  admin:    ${adminEmail} / ${adminPw}\n  licensor: demo-licensor / Licensor-Demo-123\n  books:    /api/books  (matchmaker-v1, chigaya-v1, chigaya-v2, grenimal-v1)`);
  await mongoose.disconnect();
})().catch((e) => { console.error(e); process.exit(1); });
